package com.example.minecord.fun;

/**
 * Інтерфейс для розважальних ігрових режимів та міні-ігор на сервері.
 */
public interface FunMode {
    /**
     * Унікальний текстовий ідентифікатор режиму (використовується в config.yml).
     */
    String getId();

    /**
     * Назва режиму для відображення.
     */
    String getName();

    /**
     * Короткий опис режиму.
     */
    String getDescription();

    /**
     * Чи ввімкнено цей режим у налаштуваннях.
     */
    boolean isEnabled();

    /**
     * Викликається при активації режиму (реєстрація лістенерів, запуск таймерів).
     */
    void onEnable();

    /**
     * Викликається при деактивації режиму (скидання ігор, очищення стану).
     */
    void onDisable();

    /**
     * Викликається при перезавантаженні конфігурації.
     */
    void onReload();
}